#!/usr/bin/env python3
"""Check a unit's boundaries by comparing its compiled object with the original's slice.

Unit boundaries in the modules are inferred (tools/decomp/units.py) and about
one in eight checked so far was wrong. A wrong boundary shows in the compiled
object long before the hash check fails:

  - a global function we emit that the original slice lacks, found in the
    neighbouring unit                       -> the boundary is too narrow
  - a function of the slice we can never emit (it is a weak inline or thunk of
    a class this file defines, sitting at the slice's edge)
                                            -> it belongs to the neighbour
  - .rodata / .data / .bss sizes that differ by more than alignment padding
  - a unit made only of weak inlines, template instances and thunks
                                            -> part of the file before it

Weak functions we emit that the slice lacks are normal (the linker keeps the
first copy) and are only counted.

Usage:
    python tools/decomp/boundaries.py <unit>          one unit
    python tools/decomp/boundaries.py --all           every unit with source
    python tools/decomp/boundaries.py --module BossF  every unit with source in a module
    python tools/decomp/boundaries.py --suspects M    units of module M (with or without source)
                                                      that look like a neighbour's tail
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import diff  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent.parent
SECTION = re.compile(r"^# 0x([0-9A-F]+)\.\.0x([0-9A-F]+) \| size: 0x([0-9A-F]+)$")
FN = re.compile(r'^\.fn ("[^"]+"|\S+?),\s*(\w+)')
PAD = 8


def sections(text):
    """({section: size}, [(fn, scope)])"""
    sizes, fns = {}, []
    pending = None
    for line in text.splitlines():
        m = SECTION.match(line)
        if m:
            pending = int(m.group(3), 16)
            continue
        if pending is not None:
            s = line.strip()
            name = s.split()[1].strip('",') if s.startswith(".section") else s
            if name.startswith("."):
                sizes[name] = sizes.get(name, 0) + pending
            pending = None
        m = FN.match(line)
        if m:
            fns.append((m.group(1).strip('"'), m.group(2)))
    return sizes, fns


def module_units(version, module):
    cfg = json.loads((ROOT / "build" / version / "config.json").read_text())
    entry = next(m for m in cfg["modules"] if m["name"] == module)
    return [u["name"].rsplit(".", 1)[0] for u in entry["units"] if not u["autogenerated"]]


def orig_text(version, module, unit):
    p = ROOT / "build" / version / module / "asm" / (unit + ".s")
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def is_inline_like(name):
    return name.startswith(("@", "__sinit")) or bool(re.search(r"__Q\d+\w*?(CFsm|CStateTemplate|function)", name))


def check(version, module, unit, order, scores=None):
    issues = []
    o_sizes, o_fns = sections(orig_text(version, module, unit))
    try:
        ours_text = diff.disasm_ours(version, unit)
    except SystemExit:
        return [f"no compiled object (build/{version}/src/{unit}.o)"]
    u_sizes, u_fns = sections(ours_text)
    o_names = {n for n, _ in o_fns}
    u_names = {n: s for n, s in u_fns}
    i = order.index(unit) if unit in order else -1
    neighbours = {}
    for j in (i - 1, i + 1):
        if 0 <= j < len(order):
            neighbours[order[j]] = {n for n, _ in sections(orig_text(version, module, order[j]))[1]}

    weak_extra = 0
    for name, scope in u_fns:
        if name in o_names:
            continue
        if scope == "weak":
            weak_extra += 1
            continue
        if name.startswith("__sinit_"):
            unnamed = [n for n in o_names if n.startswith("fn_")]
            issues.append(f"static initialiser {name} is unnamed in the split"
                          + (f" (probably {unnamed[-1]}): rename it in symbols.txt, unquoted" if unnamed else ""))
            continue
        where = [n for n, fns in neighbours.items() if name in fns]
        if where:
            issues.append(f"{name} is in the neighbouring unit {where[0]}: the boundary is too narrow, move it")
        else:
            issues.append(f"{name} ({scope}) is in neither this slice nor its neighbours "
                          "(stripped by the original link, misnamed, or the boundary is far off)")
    missing = [n for n, _ in o_fns if n not in u_names]
    if missing:
        # a run of missing functions at an edge of the slice may belong to a neighbour
        names = [n for n, _ in o_fns]
        head = []
        for n in names:
            if n in u_names:
                break
            head.append(n)
        tail = []
        for n in reversed(names):
            if n in u_names:
                break
            tail.append(n)
        if head and len(head) < len(names):
            issues.append(f"{len(head)} function(s) at the start of the slice are not emitted "
                          f"({head[0]} ...): not written yet, or they belong to the unit before")
        if tail and len(tail) < len(names):
            issues.append(f"{len(tail)} function(s) at the end of the slice are not emitted "
                          f"({tail[-1]} ...): not written yet, or the tail of this file / the next unit")
        inner = len(missing) - len(head) - len(tail)
        if inner > 0:
            issues.append(f"{inner} function(s) inside the slice not emitted yet")
    if not missing:
        for sec in (".text", ".rodata", ".data", ".bss"):
            a, b = o_sizes.get(sec, 0), u_sizes.get(sec, 0)
            if sec == ".text":
                # weak copies the linker drops make ours longer; only a shortfall is a sign,
                # and only when every function matches (an unfinished one may be shorter)
                if b < a and scores and all(s >= 100.0 for s in scores.values()):
                    issues.append(f".text: ours 0x{b:X}, original slice 0x{a:X}")
            elif not (a - PAD < b <= a):
                issues.append(f"{sec}: ours 0x{b:X}, original slice 0x{a:X} (more than alignment padding apart: "
                              "data belongs to a neighbour, or is missing / extra here)")
    if weak_extra:
        issues.append(f"(info) {weak_extra} weak function(s) emitted that the slice lacks; the linker keeps the first copy")
    return issues


def suspects(version, module):
    """Units whose functions are all weak-looking inlines, thunks or template instances."""
    order = module_units(version, module)
    out = []
    for unit in order:
        _, fns = sections(orig_text(version, module, unit))
        names = [n for n, _ in fns]
        if names and all(n.startswith(("@", "fn_")) or "Template" in n or "__dt__" in n or
                         re.match(r"(Get|Is|Set)\w*__Q", n) for n in names):
            out.append((unit, len(names)))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("unit", nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--module")
    ap.add_argument("--suspects")
    ap.add_argument("--version", default="RMKE01")
    args = ap.parse_args()

    if args.suspects:
        for unit, n in suspects(args.version, args.suspects):
            print(f"{args.suspects} {unit}: {n} functions, all accessor/thunk/destructor/template-like: "
                  "probably the tail of the unit before it")
        return
    units = diff.report_units(args.version)
    if args.unit:
        targets = [diff.find_unit(units, args.unit)]
    else:
        targets = [u for u, (m, _, src) in units.items() if src and m not in ("main",)
                   and (args.all or m == args.module) and u.startswith("game/")]
    orders = {}
    clean = 0
    for unit in sorted(targets):
        module = units[unit][0]
        if module not in orders:
            orders[module] = module_units(args.version, module)
        issues = check(args.version, module, unit, orders[module], units[unit][1])
        real = [i for i in issues if not i.startswith("(info)")]
        if not real:
            clean += 1
            if args.unit:
                print(f"{module}/{unit}: boundaries look right")
                for i in issues:
                    print("  " + i)
            continue
        print(f"{module}/{unit}:")
        for i in issues:
            print("  " + i)
    if not args.unit:
        print(f"\n{clean} of {len(targets)} units look right")


if __name__ == "__main__":
    main()
