#!/usr/bin/env python3
"""Print a rough C draft of one function, made by m2c from its assembly.

The draft shows control flow, field offsets and constants. It is a starting
point for writing the real source: it is not matching code, its names are
placeholders, and it knows nothing of the project's headers unless given.

Usage:
    python tools/decomp/draft.py <function> [--module <Module>] [--context <header.h>]

Needs m2c:  py -3.12 -m pip install --user git+https://github.com/matt-kempster/m2c.git
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
CR_BITS = {"lt": 0, "gt": 1, "eq": 2, "un": 3, "so": 3}
CR_OP = re.compile(r"\t(cr(?:or|and|xor|nor|nand|eqv|andc|orc))\s+(.*)$")


def cr_bit(tok):
    m = re.fullmatch(r"(?:4\*cr(\d)\+)?(lt|gt|eq|un|so)", tok.strip())
    return str(int(m.group(1) or 0) * 4 + CR_BITS[m.group(2)]) if m else tok.strip()


def clean(text, keep):
    """Keep only function `keep` (and all data), in a form m2c reads.

    dtk names condition-register bits where m2c wants numbers, and one odd
    instruction elsewhere in a file would stop m2c from reading any of it.
    """
    out = []
    skipping = False
    for line in text.splitlines():
        if line.startswith(".fn "):
            rest = line[4:].strip()
            name = rest[1:rest.index('"', 1)] if rest.startswith('"') else rest.split(",")[0].strip()
            skipping = name != keep
        if skipping:
            skipping = not line.startswith(".endfn")
            continue
        if line.startswith('.section .init'):
            line = ".text"
        m = CR_OP.search(line)
        if m:
            line = line[:m.start()] + f"\t{m.group(1)} " + ", ".join(cr_bit(t) for t in m.group(2).split(","))
        out.append(line)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("function")
    ap.add_argument("--module")
    ap.add_argument("--version", default="RMKE01")
    ap.add_argument("--context", help="preprocessed header with the types the function uses")
    args = ap.parse_args()

    base = ROOT / "build" / args.version
    index = json.loads((ROOT / "build" / "decomp" / f"index_{args.version}.json").read_text(encoding="utf-8"))
    hits = [f for f in index if f["name"] == args.function and args.module in (None, f["module"])]
    if not hits:
        sys.exit(f"{args.function} not found in the index (rebuild it with tools/decomp/index.py)")
    if len({(f["module"], f["unit"]) for f in hits}) > 1:
        sys.exit("found in: " + ", ".join(sorted({f["module"] for f in hits})) + "; pass --module")
    module, unit = hits[0]["module"], hits[0]["unit"]
    asm = base / "asm" if module == "main" else base / module / "asm"
    files = [asm / (unit + ".s")]
    if unit.startswith("auto_"):
        # an unsplit unit keeps its literals in separate auto-generated files
        cfg = json.loads((base / "config.json").read_text())
        entry = cfg if module == "main" else next(m for m in cfg["modules"] if m["name"] == module)
        files += [asm / (u["name"] + ".s") for u in entry["units"]
                  if u["autogenerated"] and re.search(r"_(rodata|sdata2|data|sdata)$", u["name"])]

    work = ROOT / "build" / "decomp" / "draft"
    work.mkdir(parents=True, exist_ok=True)
    inputs = []
    for n, path in enumerate(p for p in files if p.exists()):
        dest = work / f"{n}.s"
        dest.write_text(clean(path.read_text(encoding="utf-8", errors="replace"), args.function),
                        encoding="utf-8")
        inputs.append(str(dest))
    cmd = [sys.executable, "-m", "m2c.main", "-t", "ppc-mwcc-c++", "-f", args.function]
    if args.context:
        cmd += ["--context", args.context]
    try:
        res = subprocess.run(cmd + inputs, capture_output=True, text=True, timeout=120)
    except subprocess.TimeoutExpired:
        sys.exit("m2c took longer than 120 s on this function; work from the assembly instead")
    if "No module named" in res.stderr:
        sys.exit("m2c is not installed: py -3.12 -m pip install --user "
                 "git+https://github.com/matt-kempster/m2c.git")
    sys.stdout.write(res.stdout)
    if res.returncode:
        sys.stderr.write(res.stderr[-2000:])
    return res.returncode


if __name__ == "__main__":
    sys.exit(main())
