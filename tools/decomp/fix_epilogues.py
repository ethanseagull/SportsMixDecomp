#!/usr/bin/env python3
"""Fold dead epilogue `blr`s back into the function before them.

RSO export tables carry no sizes, so the split ends an exported function at
its last branch. When the function ends in a tail call (`b` or `bctr`) after an
early return, the compiler still emits the epilogue `blr` behind it, and the
split gives that dead `blr` a symbol of its own (`fn_<module>_<addr>`, size 4).
objdiff then scores the real function at ~90% and the `fn_` at 0% although the
compiled code is byte-identical (notes/toolchain.md, "Unnamed 4-byte blr").

A 4-byte `fn_` is folded when all of these hold:
  - its only instruction is `blr`;
  - the function before it ends exactly at its address and its last
    instruction is an unconditional `b <label/symbol>` or `bctr`;
  - nothing in the module refers to the `fn_` symbol (a real empty function
    would be named by a vtable, a call or a pointer table).

Folding deletes the `fn_` line from the module's symbols.txt and adds 4 to the
size of the function before it. Code bytes do not change, so the hash check is
unaffected; run the full build afterwards anyway.

Usage:
    python tools/decomp/fix_epilogues.py              report only
    python tools/decomp/fix_epilogues.py --apply      edit symbols.txt
    python tools/decomp/fix_epilogues.py --module MenuF [--apply]
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
INSN = re.compile(r"^/\* ([0-9A-F]{8}) \S+  (?:[0-9A-F]{2} ){4}\*/\t(\S+)(?:\s+(.*))?$")
SYM_LINE = re.compile(r"^(\S+) = \.text:0x([0-9A-Fa-f]+); // type:function size:0x([0-9A-Fa-f]+)(.*)$")


def module_asm(version, module):
    """Yield (functions in address order, full asm text) for one module."""
    base = ROOT / "build" / version
    cfg = json.loads((base / "config.json").read_text())
    entry = next(m for m in cfg["modules"] if m["name"] == module)
    funcs, texts = [], []
    for u in entry["units"]:
        unit = u["name"] if u["autogenerated"] else u["name"].rsplit(".", 1)[0]
        path = base / module / "asm" / (unit + ".s")
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        texts.append(text)
        cur = None
        for line in text.splitlines():
            if line.startswith(".fn "):
                rest = line[4:].strip()
                name = rest[1:rest.index('"', 1)] if rest.startswith('"') else rest.split(",")[0].strip()
                cur = {"name": name, "insns": []}
            elif line.startswith(".endfn") and cur:
                if cur["insns"]:
                    cur["start"] = cur["insns"][0][0]
                    cur["end"] = cur["insns"][-1][0] + 4
                    funcs.append(cur)
                cur = None
            elif cur is not None:
                m = INSN.match(line)
                if m:
                    cur["insns"].append((int(m.group(1), 16), m.group(2), m.group(3) or ""))
    funcs.sort(key=lambda f: f["start"])
    return funcs, "\n".join(texts)


def candidates(funcs, text):
    out = []
    for prev, f in zip(funcs, funcs[1:]):
        if not re.fullmatch(r"fn_\d+_[0-9A-F]+", f["name"]):
            continue
        if len(f["insns"]) != 1 or f["insns"][0][1] != "blr":
            continue
        if prev["end"] != f["start"]:
            continue
        last = prev["insns"][-1]
        if not (last[1] == "bctr" or (last[1] == "b" and last[2])):
            continue
        # references other than its own .fn/.endfn lines and the comment header
        refs = len(re.findall(r"(?<![\w.$@])" + re.escape(f["name"]) + r"(?![\w$@])", text))
        if refs > 2:
            continue
        out.append((prev["name"], f["name"], f["start"]))
    return out


def apply(version, module, folds):
    path = ROOT / "config" / version / module / "symbols.txt"
    lines = path.read_text(encoding="utf-8").splitlines(True)
    drop = {fn for _, fn, _ in folds}
    grow = {prev for prev, _, _ in folds}
    out, changed = [], 0
    for line in lines:
        m = SYM_LINE.match(line.rstrip("\n"))
        if m and m.group(1) in drop:
            changed += 1
            continue
        if m and m.group(1) in grow:
            size = int(m.group(3), 16) + 4
            line = f"{m.group(1)} = .text:0x{m.group(2)}; // type:function size:0x{size:X}{m.group(4)}\n"
        out.append(line)
    path.write_text("".join(out), encoding="utf-8", newline="\n")
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--module", action="append")
    ap.add_argument("--version", default="RMKE01")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()
    cfg = json.loads((ROOT / "build" / args.version / "config.json").read_text())
    modules = args.module or [m["name"] for m in cfg["modules"]]
    total = 0
    for module in modules:
        funcs, text = module_asm(args.version, module)
        folds = candidates(funcs, text)
        total += len(folds)
        print(f"{module}: {len(folds)} dead epilogues")
        if args.verbose:
            for prev, fn, addr in folds:
                print(f"  {fn} -> {prev}")
        if args.apply and folds:
            n = apply(args.version, module, folds)
            print(f"  folded {n} in config/{args.version}/{module}/symbols.txt")
    print(f"total {total}" + ("" if args.apply else " (report only; --apply to edit)"))


if __name__ == "__main__":
    main()
