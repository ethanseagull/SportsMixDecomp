#!/usr/bin/env python3
"""Recover a class's layout from every function in the game that touches it.

Headers were the slowest part of the 2026-11-09 runs: a unit cannot compile
until the classes it uses have the right members at the right offsets, and
those were pieced together by hand from one unit's functions at a time. This
reads the split assembly of the DOL and all modules at once and reports, for
one class:

  size      from `li r3, N` / `bl __nw__FUl` followed by its constructor or a
            store of its vtable (every module that creates one)
  bases     constructors called on `this` from its own constructor
  vptr      offset where the constructor stores the class's vtable
  vtable    every slot, demangled, with the class that implements it
  fields    every load, store and address-of through `this` in the class's
            own member functions: offset, access width/type, how many
            functions, an example

`this` is tracked per function from r3 at entry through `mr` copies; any other
write to a register, or a call (volatile registers), drops it. Branches are
ignored, so a register reused on another path can add a stray field: check
odd offsets before trusting them. Static member functions are skipped when
they never use r3 as a base.

Usage:
    python tools/decomp/layout.py msw::CChrCore
    python tools/decomp/layout.py msw::CChrCore --header   draft C++ class body
    python tools/decomp/layout.py msw::CChrCore --who 0x174 functions touching one offset
    python tools/decomp/layout.py msw::CChrCoreBoss --module BossF
"""
import argparse
import json
import pickle
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
INSN = re.compile(r"^/\* \S+ \S+  (?:[0-9A-F]{2} ){4}\*/\t(\S+)(?:\s+(.*))?$")
MEM = re.compile(r"^(-?(?:0x)?[0-9a-fA-F]+)\((r\d+)\)$")
LOADS = {"lwz": "u32", "lwzu": "u32", "lbz": "u8", "lhz": "u16", "lha": "s16",
         "lfs": "f32", "lfd": "f64", "psq_l": "ps"}
STORES = {"stw": "u32", "stwu": "u32", "stb": "u8", "sth": "u16", "stfs": "f32",
          "stfd": "f64", "psq_st": "ps"}
CTYPE = {"u32": "unsigned long", "u8": "unsigned char", "u16": "unsigned short",
         "s16": "short", "f32": "float", "f64": "double", "ps": "float"}
WIDTH = {"u32": 4, "u8": 1, "u16": 2, "s16": 2, "f32": 4, "f64": 8, "ps": 8}
CACHE = ROOT / "build" / "decomp" / "layout_cache.pickle"


def mangle_class(qual):
    parts = qual.split("::")
    toks = "".join(f"{len(p)}{p}" for p in parts)
    return toks if len(parts) == 1 else f"Q{len(parts)}{toks}"


def asm_files(version):
    base = ROOT / "build" / version
    cfg = json.loads((base / "config.json").read_text())
    for entry in [cfg] + cfg["modules"]:
        module = "main" if entry is cfg else entry["name"]
        asm_dir = base / "asm" if entry is cfg else base / module / "asm"
        for u in entry["units"]:
            unit = u["name"] if u["autogenerated"] else u["name"].rsplit(".", 1)[0]
            path = asm_dir / (unit + ".s")
            if path.exists():
                yield module, unit, path


def load(version):
    """functions: [(module, unit, name, [(mnemonic, operands)])], objects, demangled names."""
    stamp = (ROOT / "build" / version / "config.json").stat().st_mtime
    if CACHE.exists():
        data = pickle.loads(CACHE.read_bytes())
        if data.get("stamp") == stamp:
            return data
    funcs, objs, names = [], {}, {}
    for module, unit, path in asm_files(version):
        cur = obj = None
        comment = None
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("# ") and not line.startswith("# ."):
                comment = line[2:].strip()
                continue
            if line.startswith(".fn "):
                rest = line[4:].strip()
                name = rest[1:rest.index('"', 1)] if rest.startswith('"') else rest.split(",")[0].strip()
                if comment and "(" in comment:
                    names[name] = comment
                cur = (module, unit, name, [])
            elif line.startswith(".endfn") and cur:
                funcs.append(cur)
                cur = None
            elif cur is not None:
                m = INSN.match(line)
                if m:
                    cur[3].append((m.group(1), m.group(2) or ""))
            elif line.startswith(".obj "):
                oname = line[5:].split(",")[0].strip().strip('"')
                obj = (module, oname, [])
            elif line.startswith(".endobj") and obj:
                objs.setdefault(obj[1], (obj[0], obj[2]))
                obj = None
            elif obj is not None and line.strip().startswith(".4byte"):
                obj[2].append(line.strip()[6:].strip())
            if not line.startswith("# "):
                comment = None
    data = {"stamp": stamp, "funcs": funcs, "objs": objs, "names": names}
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_bytes(pickle.dumps(data))
    return data


def regs_written(mn, ops):
    """Registers an instruction overwrites (first operand of most non-store ops)."""
    if mn.startswith(("st", "psq_st", "cmp", "b", "mt", "dcb", "icb", "sync", "isync", "tw")):
        return set()
    first = ops.split(",")[0].strip()
    return {first} if re.fullmatch(r"r\d+", first) else set()


def this_accesses(insns):
    """[(offset, kind)] for accesses through `this` (r3 at entry)."""
    alias = {"r3"}
    out = []
    used = False
    for mn, ops in insns:
        parts = [p.strip() for p in ops.split(",")]
        if mn in LOADS or mn in STORES:
            m = MEM.match(parts[1]) if len(parts) > 1 else None
            if m and m.group(2) in alias:
                off = int(m.group(1), 0)
                if not (mn in ("stwu",) and m.group(2) == "r1"):
                    out.append((off, (LOADS.get(mn) or STORES.get(mn)), "load" if mn in LOADS else "store"))
                    used = True
        elif mn == "addi" and len(parts) == 3 and parts[1] in alias:
            try:
                off = int(parts[2], 0)
            except ValueError:
                off = None
            if off is not None and off > 0:
                out.append((off, "addr", "addr"))
                used = True
        if mn == "mr" and len(parts) == 2:
            if parts[1] in alias:
                alias.add(parts[0])
            else:
                alias.discard(parts[0])
            continue
        if mn in ("bl", "bctrl", "blrl"):
            alias -= {f"r{i}" for i in range(3, 13)}
            continue
        if mn in LOADS and len(parts) > 0:
            alias.discard(parts[0])  # a load into an alias register replaces it
            continue
        alias -= regs_written(mn, ops)
    return out if used else []


def demangle(data, sym):
    return data["names"].get(sym, sym)


def analyse(data, qual, module=None):
    tok = mangle_class(qual)
    member = re.compile(r"__" + re.escape(tok) + r"(?:C?F|$)")
    ctor = f"__ct__{tok}"
    vt = f"__vt__{tok}"
    res = {"tok": tok, "fields": defaultdict(lambda: {"kinds": Counter(), "fns": set()}),
           "sizes": Counter(), "bases": Counter(), "vptr": Counter(), "members": []}
    for mod, unit, name, insns in data["funcs"]:
        if module and mod != module:
            continue
        if member.search(name):
            res["members"].append((mod, name))
            for off, kind, how in this_accesses(insns):
                f = res["fields"][off]
                f["kinds"][kind] += 1
                f["fns"].add(name)
            if name.startswith(ctor):
                for i, (mn, ops) in enumerate(insns):
                    if mn == "bl" and ops.startswith("__ct__") and not ops.startswith(ctor):
                        res["bases"][ops] += 1
                    if mn == "addi" and vt + "@l" in ops:
                        reg = ops.split(",")[0].strip()
                        for mn2, ops2 in insns[i + 1:i + 6]:
                            if mn2 == "stw" and ops2.startswith(reg + ","):
                                m = MEM.match(ops2.split(",")[1].strip())
                                if m:
                                    res["vptr"][int(m.group(1), 0)] += 1
                                break
        # allocation sites: li r3, N ; bl __nw__FUl ; ... __ct__tok or __vt__tok
        for i, (mn, ops) in enumerate(insns):
            if mn == "bl" and ops.startswith("__nw__") and i > 0:
                pmn, pops = insns[i - 1]
                if pmn != "li" or not pops.startswith("r3,"):
                    continue
                for mn2, ops2 in insns[i + 1:i + 40]:
                    if mn2 == "bl" and ops2.startswith("__nw__"):
                        break
                    if (mn2 == "bl" and ops2.startswith(ctor + "F")) or (vt + "@") in ops2:
                        res["sizes"][int(pops.split(",")[1], 0)] += 1
                        break
    res["vtable"] = data["objs"].get(vt)
    return res


def owner(sym):
    m = re.search(r"__(Q\d(?:\d+\w+?)+|\d+\w+?)(?:C?F|$)", sym)
    return m.group(1) if m else ""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cls", help="qualified class name, e.g. msw::CChrCore")
    ap.add_argument("--module")
    ap.add_argument("--version", default="RMKE01")
    ap.add_argument("--header", action="store_true")
    ap.add_argument("--who", help="offset: list the functions touching it")
    ap.add_argument("--min", type=int, default=0, help="skip offsets below this (base class part)")
    args = ap.parse_args()
    data = load(args.version)
    r = analyse(data, args.cls, args.module)

    if args.who:
        off = int(args.who, 0)
        f = r["fields"].get(off)
        if not f:
            raise SystemExit(f"nothing touches {args.who}")
        print(f"{args.cls} +0x{off:X}: {dict(f['kinds'])}")
        for n in sorted(f["fns"]):
            print("  " + demangle(data, n))
        return

    print(f"{args.cls}  ({r['tok']}): {len(r['members'])} member functions")
    if r["sizes"]:
        print("size:   " + ", ".join(f"0x{s:X} (x{c})" for s, c in r["sizes"].most_common()))
    else:
        print("size:   no allocation site found (embedded, static, or created through a factory)")
    if r["bases"]:
        print("bases:  " + ", ".join(f"{demangle(data, b)}" for b, _ in r["bases"].most_common()))
    if r["vptr"]:
        print("vptr:   " + ", ".join(f"0x{o:X}" for o in r["vptr"]))
    if r["vtable"]:
        mod, slots = r["vtable"]
        print(f"vtable: {len(slots)} words (from {mod})")
        if not args.header:
            for i, s in enumerate(slots):
                print(f"  [{i:3d}] +0x{4 * i:03X}  {demangle(data, s) if s not in ('0x00000000',) else '0'}")
    fields = sorted((o, f) for o, f in r["fields"].items() if o >= args.min)
    if not args.header:
        print(f"fields: {len(fields)} offsets")
        for off, f in fields:
            kinds = ",".join(f"{k}x{c}" for k, c in f["kinds"].most_common())
            ex = demangle(data, sorted(f["fns"])[0])
            print(f"  +0x{off:04X}  {kinds:24s} {len(f['fns']):3d} fn  e.g. {ex[:70]}")
        return

    # Draft header body.
    size = r["sizes"].most_common(1)[0][0] if r["sizes"] else None
    cls = args.cls.split("::")[-1]
    print(f"\n// Draft from tools/decomp/layout.py; names are placeholders, types are guessed from access width.")
    print(f"class {cls} {{")
    print("    public:")
    if r["vtable"]:
        own = r["tok"]
        for s in r["vtable"][1][2:]:
            if s.startswith("0x"):
                continue
            d = demangle(data, s)
            sig = d.split("::")[-1] if "::" in d else d
            mark = "" if owner(s) == own else f"  // inherited: {d.rsplit('::', 1)[0]}"
            print(f"        virtual {sig};{mark}")
    print("    private:")
    pos = args.min
    vptrs = set(r["vptr"])
    for off, f in fields:
        if off < pos:
            continue
        if off in vptrs:
            continue
        if off > pos:
            print(f"        char m_Pad{pos:02X}[0x{off - pos:X}];")
        kind = f["kinds"].most_common(1)[0][0]
        if kind == "addr":
            nxt = next((o for o, _ in fields if o > off), size or off + 4)
            print(f"        char m_Obj{off:02X}[0x{nxt - off:X}]; // embedded object (address taken)")
            pos = nxt
            continue
        print(f"        {CTYPE[kind]} m_Unk{off:02X}; // 0x{off:X}")
        pos = off + WIDTH[kind]
    if size and size > pos:
        print(f"        char m_Pad{pos:02X}[0x{size - pos:X}];")
    print(f"}}; // size 0x{size:X}" if size else "}; // size unknown")


if __name__ == "__main__":
    main()
