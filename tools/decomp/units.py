#!/usr/bin/env python3
"""Propose source-file (unit) boundaries for a module.

A freshly split module is one big unit. This tool reads its split assembly and
infers where the original source files began and ended, from evidence the
compiler and linker left behind:

  pad     a data section is padded to 8 bytes where the next object only needs
          4: the next object starts a new file.
  dup     the compiler stores each float/double/string literal once per file,
          so two identical literals lie in different files.
  share   two functions that use the same unnamed data object are in one file.
  order   files appear in the same order in every section, so a function's
          literals bound where its file can sit in the data sections.
  class   member functions of one class that sit together are usually one file.
  sinit   a static-initialiser listed in .ctors is the last function of a file.

Usage:
    python tools/decomp/units.py <Module>            summary and unit list
    python tools/decomp/units.py <Module> --splits   print splits.txt entries
    python tools/decomp/units.py <Module> --apply    add them to the module's splits.txt
    python tools/decomp/units.py --all [--apply]

Proposals are evidence-ranked guesses. Any split still rebuilds byte-exact;
a wrong boundary only shows when the unit's source is written, and is fixed
then by moving the line in splits.txt.
"""
import argparse
import bisect
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MODULES = ["SystemF", "MenuF", "TourF", "BasketF", "VolleyF", "DodgeF", "HockeyF", "BossF", "DebugF"]
DATA_SECTIONS = [".rodata", ".data", ".bss"]
UNIT_ALIGN = 8

HEAD = re.compile(r"^# (\.\w+):0x[0-9A-F]+ \| 0x([0-9A-F]+) \| size: 0x([0-9A-F]+)")
OPEN = re.compile(r'^\.(fn|obj) (?:"([^"]+)"|([^,\s]+)), (\w+)')
INSN = re.compile(r"^/\* \S+ \S+  (?:[0-9A-F]{2} ){4}\*/\t\S+(?:\s+(.*))?$")
QUOTED = re.compile(r'"([^"]+)"')
WORD = re.compile(r"[A-Za-z_@$][\w@$.<>,*&:~-]*")
PRIVATE = re.compile(r"^(lbl_|jumptable_|gap_|@\d+$|@stringBase|@LOCAL@)")


class Item:
    __slots__ = ("section", "addr", "size", "name", "kind", "refs", "body", "file")

    def __init__(self, section, addr, size, name, kind, file):
        self.section, self.addr, self.size = section, addr, size
        self.name, self.kind, self.file = name, kind, file
        self.refs = set()
        self.body = []

    @property
    def end(self):
        return self.addr + self.size

    @property
    def private(self):
        return bool(PRIVATE.match(self.name))

    @property
    def is_gap(self):
        return self.name.startswith("gap_")


def operand_symbols(text):
    out = set(QUOTED.findall(text))
    text = QUOTED.sub(" ", text)
    for w in WORD.findall(text):
        out.add(w.split("@ha")[0].split("@l")[0].split("@h")[0] if not w.startswith("@") else w)
    return out


def parse_module(version, module):
    """Return {section: [Item sorted by addr]} and the list of .ctors targets."""
    asm = ROOT / "build" / version / module / "asm"
    if not asm.is_dir():
        sys.exit(f"{asm} not found: run the build once so the module is split")
    # Only the units of the last successful split; older .s files stay on disk.
    cfg = ROOT / "build" / version / "config.json"
    if not cfg.exists():
        sys.exit(f"{cfg} not found: run the build once")
    entry = next((m for m in json.loads(cfg.read_text())["modules"] if m["name"] == module), None)
    if entry is None:
        sys.exit(f"{module} is not in {cfg}")
    paths = [asm / (u["name"].rsplit(".", 1)[0] if not u["autogenerated"] else u["name"]) for u in entry["units"]]
    paths = [q.parent / (q.name + ".s") for q in paths]
    splits = ROOT / "config" / version / module / "splits.txt"
    if splits.exists() and splits.stat().st_mtime > cfg.stat().st_mtime:
        print(f"warning: {module}/splits.txt is newer than the last split; rebuild first", file=sys.stderr)
    found = {}
    ctors = []
    for path in paths:
        if not path.exists():
            continue
        unit = path.relative_to(asm).with_suffix("").as_posix()
        pending = None
        cur = None
        in_ctors = False
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith(".section .ctors"):
                in_ctors = True
            elif line.startswith((".section", ".text", ".rodata", ".data", ".bss")):
                in_ctors = False
            m = HEAD.match(line)
            if m:
                pending = (m.group(1), int(m.group(2), 16), int(m.group(3), 16))
                continue
            m = OPEN.match(line)
            if m and pending:
                cur = Item(pending[0], pending[1], pending[2], m.group(2) or m.group(3), m.group(1), unit)
                found[(cur.section, cur.addr)] = cur
                pending = None
                continue
            if line.startswith((".endfn", ".endobj")):
                cur = None
                continue
            if cur is None:
                if in_ctors and line.startswith("\t.4byte"):
                    ctors.extend(operand_symbols(line.split(None, 1)[1]))
                continue
            if cur.kind == "fn":
                m = INSN.match(line)
                if m and m.group(1):
                    cur.refs |= operand_symbols(m.group(1))
            elif line.startswith("\t."):
                cur.body.append(line.strip())
                parts = line.split(None, 1)
                if parts[0] in (".4byte", ".rel") and len(parts) > 1:
                    cur.refs |= operand_symbols(parts[1])
    sections = defaultdict(list)
    for key in sorted(found):
        sections[key[0]].append(found[key])
    return sections, ctors


# --- mangled names ---------------------------------------------------------

def _qualified(s, pos):
    """Parse a CodeWarrior qualified name at s[pos:]; return (parts, next pos) or None."""
    def one(p):
        m = re.match(r"\d+", s[p:])
        if not m:
            return None
        n = int(m.group())
        start = p + len(m.group())
        if n == 0 or start + n > len(s):
            return None
        return s[start:start + n], start + n

    if pos < len(s) and s[pos] == "Q" and pos + 1 < len(s) and s[pos + 1].isdigit():
        count, p, parts = int(s[pos + 1]), pos + 2, []
        for _ in range(count):
            r = one(p)
            if not r:
                return None
            parts.append(r[0])
            p = r[1]
        return parts, p
    r = one(pos)
    return ([r[0]], r[1]) if r else None


def owner(name):
    """Class that a mangled function or object name belongs to, as a tuple of parts."""
    if name.startswith("@LOCAL@"):
        return owner(name[7:].split("@")[0])
    m = re.match(r"^@\d+@(?:\d+@)?(.*)$", name)  # this-adjusting thunk
    if m:
        name = m.group(1)
    start = 1
    while True:
        i = name.find("__", start)
        if i < 0:
            return None
        r = _qualified(name, i + 2)
        if r and (r[1] == len(name) or name[r[1]] in "FC"):
            return tuple(r[0])
        start = i + 1


def is_template(parts):
    return any("<" in p for p in parts)


NAMESPACES = {"msw", "bcs", "nw4r", "std", "EGG", "snd", "lyt", "g3d", "ut", "math", "ef"}
ENGINE = {"bcs", "nw4r", "std", "EGG"}  # live in main.dol; in a module they are inline copies


def glue_key(name, classes=None):
    """Class used to group a function with its neighbours, or None.

    Templates group with their innermost template argument, so
    bcs::CFsm<msw::CFoo> counts as CFoo. Engine classes and free functions
    say nothing about which file they sit in. `classes` is the set of
    qualified names that have a constructor or destructor: an outer name
    without one (msw::SelectMenu) is a namespace and is skipped.
    """
    parts = owner(name)
    if not parts:
        return None
    joined = "::".join(parts)
    if "<" in joined:
        inner = joined[joined.rfind("<") + 1:].split(">")[0].split(",")[0]
        r = _qualified(inner, 0)
        if not r:
            return None
        parts = tuple(r[0])
    if parts[0] in ENGINE:
        return None
    i = 0
    while i < len(parts) and parts[i] in NAMESPACES:
        i += 1
    if classes is not None:
        while i < len(parts) - 1 and parts[:i + 1] not in classes:
            i += 1
    return "::".join(parts[:i + 1]).split("<")[0] if i < len(parts) else None


def literal_value(item):
    """Value of a compiler-pooled literal, or None if the object is something else."""
    if len(item.body) == 1 and item.body[0].split()[0] in (".float", ".double", ".string"):
        return item.body[0]
    return None


# --- analysis --------------------------------------------------------------

class Unit:
    def __init__(self, lo, hi):
        self.lo, self.hi = lo, hi      # function index range [lo, hi)
        self.name = None
        self.fixed = False             # already in splits.txt
        self.ranges = {}               # section -> (start, end)
        self.flags = []


class Analysis:
    def __init__(self, version, module, class_gap=16):
        self.version, self.module, self.class_gap = version, module, class_gap
        self.sections, self.ctors = parse_module(version, module)
        self.text = self.sections.get(".text", [])
        self.n = len(self.text)
        self.fidx = {f.name: i for i, f in enumerate(self.text)}
        self.data = {it.name: it for s in DATA_SECTIONS for it in self.sections.get(s, [])}
        self.classes = {owner(f.name) for f in self.text
                        if f.name.startswith(("__ct__", "__dt__")) and owner(f.name)}
        self.keys = [glue_key(f.name, self.classes) for f in self.text]
        self.sinits = sorted(self.fidx[c] for c in self.ctors if c in self.fidx)
        self.notes = []
        self.evidence = defaultdict(int)
        self._refs()
        self.hard = self._hard_cuts()
        self._link()
        self._absorb_loose()
        self._absorb_tails()
        self._ranges()
        self._finish()

    # --- evidence gathering ---

    def _refs(self):
        self.users = defaultdict(list)   # unnamed object -> functions using it
        self.fdata = []                  # function -> section -> unnamed objects used
        self.callers = defaultdict(set)
        for i, f in enumerate(self.text):
            mine = defaultdict(list)
            for r in f.refs:
                it = self.data.get(r)
                if it is not None and it.private and not it.is_gap:
                    mine[it.section].append(it)
                    self.users[it.name].append(i)
                j = self.fidx.get(r)
                if j is not None and j != i:
                    self.callers[j].add(i)
            self.fdata.append(mine)

    def _hard_cuts(self):
        """Function indexes where a unit starts for certain."""
        cuts = {0, self.n}
        if "_prolog" in self.fidx:
            cuts.add(self.fidx["_prolog"])
        for i in range(1, self.n):
            if self.text[i].file != self.text[i - 1].file:  # an existing split
                cuts.add(i)
        return cuts

    def _join(self, a, b, reason):
        """Record that functions a..b are one unit."""
        if any(c in self.hard for c in range(a + 1, b + 1)):
            self.notes.append(f"{reason}: evidence crosses a fixed boundary near {self.text[a].name}")
            return
        fresh = False
        for c in range(a + 1, b + 1):
            fresh |= not self.joined[c]
            self.joined[c] = True
        if fresh:
            self.evidence[reason] += 1

    def _link(self):
        self.joined = [False] * (self.n + 1)   # joined[i]: functions i-1 and i are one unit
        for i in range(1, self.n):             # units already in splits.txt stay whole
            f = self.text[i].file
            if f == self.text[i - 1].file and not f.startswith("auto_"):
                self.joined[i] = True
        for us in self.users.values():
            if len(us) > 1:
                self._join(min(us), max(us), "share")
        # a static initialiser is emitted after the code of its file
        for i in self.sinits:
            if i > 0 and i not in self.hard and not self.joined[i]:
                self.joined[i] = True
                self.evidence["sinit"] += 1
        self.shared = list(self.joined)   # the certain part

        # A class's home is its heaviest run of functions; copies elsewhere are inlines.
        by_key = defaultdict(list)
        for i, k in enumerate(self.keys):
            if k:
                by_key[k].append(i)
        self.home = {}
        pairs = []
        size = lambda c: sum(self.text[i].size for i in c)
        for k, idx in by_key.items():
            clusters, cur = [], [idx[0]]
            for a, b in zip(idx, idx[1:]):
                if b - a <= self.class_gap and not any(c in self.hard for c in range(a + 1, b + 1)):
                    cur.append(b)
                else:
                    clusters.append(cur)
                    cur = [b]
            clusters.append(cur)
            best = max(clusters, key=size)
            if size(best) * 2 >= sum(size(c) for c in clusters):
                self.home[k] = (best[0], best[-1])
                pairs.extend((b - a, a, b) for a, b in zip(best, best[1:]))
        # closest pairs first; a link that would put two static initialisers or a
        # repeated literal into one file is refused
        for _, a, b in sorted(pairs):
            if all(self.joined[c] for c in range(a + 1, b + 1)):
                continue
            lo, hi = self._extent(a), self._extent(b)
            if self._possible(lo[0], hi[1]):
                self._join(a, b, "class")
            else:
                self.evidence["refused"] += 1

    def _extent(self, i):
        """The block [lo, hi) that function i is in at the moment."""
        lo = i
        while self.joined[lo]:
            lo -= 1
        hi = i + 1
        while hi < self.n and self.joined[hi]:
            hi += 1
        return lo, hi

    def _possible(self, lo, hi):
        """Could functions lo..hi-1 come from one source file?"""
        k = bisect.bisect_left(self.sinits, lo)
        if k + 1 < len(self.sinits) and self.sinits[k + 1] < hi:
            return False
        seen = {}
        for i in range(lo, hi):
            for it in self.fdata[i].get(".rodata", ()):
                v = literal_value(it)
                if v is not None and seen.setdefault(v, it.addr) != it.addr:
                    return False
        return True

    def _absorb_tails(self):
        """Inherited virtuals a class never overrides are emitted after it, for its vtable."""
        vt_users = defaultdict(set)   # function -> classes whose vtable lists it
        for it in self.sections.get(".data", []) + self.sections.get(".rodata", []):
            if it.name.startswith("__vt__"):
                k = glue_key(it.name, self.classes)
                for r in it.refs:
                    if r in self.fidx and k:
                        vt_users[self.fidx[r]].add(k)
        starts = self._starts()
        for s, e in zip(starts[1:], starts[2:] + [self.n]):
            if s in self.hard or any(self.fdata[i] for i in range(s, e)):
                continue
            plo, _ = self._extent(s - 1)
            homed = self._home_keys(plo, s)
            if all(vt_users.get(i, set()) & homed or self.text[i].name.startswith("@")
                   for i in range(s, e)) and self._possible(plo, e):
                self.joined[s] = True
                self.evidence["vtable"] += 1

    def _absorb_loose(self):
        """Attach single functions that carry no evidence to the block before or after."""
        starts = [i for i in range(self.n) if not self.joined[i]]
        ends = starts[1:] + [self.n]
        loose = []
        for s, e in zip(starts, ends):
            k = self.keys[s]
            at_home = k is not None and self.home.get(k, (-1,))[0] == s
            if e - s == 1 and not at_home and self.text[s].name != "_prolog":
                loose.append(s)
        loose_set = set(loose)
        i = 0
        while i < len(loose):
            run = [loose[i]]
            while i + 1 < len(loose) and loose[i + 1] == run[-1] + 1 and loose[i + 1] not in self.hard:
                i += 1
                run.append(loose[i])
            i += 1
            first, after = run[0], run[-1] + 1
            has_prev = first not in self.hard
            has_next = after not in self.hard and after < self.n
            if not has_prev and not has_next:
                for r in run[1:]:
                    self.joined[r] = True
                continue
            if not has_next:
                cut = len(run)
            elif not has_prev:
                cut = 0
            else:
                cut = self._split_run(run, starts, ends)
            for r in run[:cut]:
                if not self._possible(self._extent(r - 1)[0], r + 1):
                    break
                self.joined[r] = True          # tail of the block before
            for r in reversed(run[cut:]):
                if self._possible(r, self._extent(r + 1)[1]):
                    self.joined[r + 1] = True  # head of the block after

    def _split_run(self, run, starts, ends):
        """How many functions of a loose run belong to the block before it."""
        first, after = run[0], run[-1] + 1
        prev_lo = starts[bisect.bisect_right(starts, first - 1) - 1]
        next_hi = ends[bisect.bisect_right(starts, after) - 1]
        if self.text[prev_lo].name == "_prolog" and prev_lo == first - 1 or \
                self.text[first - 1].name in ("_unresolved", "_epilog", "_prolog"):
            # the module's own file holds only its entry points
            cut = 0
            while cut < len(run) and owner(self.text[run[cut]].name) is None \
                    and not self.text[run[cut]].name.startswith("fn_"):
                cut += 1
            return cut
        cut = len(run)
        # the compiler emits inline base destructors just before the destructor that needs them
        if self.text[after].name.startswith(("__dt__", "__ct__")):
            while cut > 0 and self.text[run[cut - 1]].name.startswith("__dt__") \
                    and run[cut - 1] not in self.sinits:
                cut -= 1
        while cut > 0:
            f = run[cut - 1]
            cs = self.callers.get(f, ())
            used_after = any(after <= c < next_hi for c in cs)
            used_before = any(prev_lo <= c < first for c in cs)
            if used_after and not used_before and f not in self.sinits:
                cut -= 1
            else:
                break
        return cut

    # --- data sections ---

    def _starts(self):
        return [i for i in range(self.n) if not self.joined[i]]

    def _ranges(self):
        """Slice the data sections between the blocks; merge blocks that cannot be separated."""
        self.unsplit = set()
        while True:
            starts = self._starts()
            ends = starts[1:] + [self.n]
            again = False
            self.bounds = {}
            for s in DATA_SECTIONS:
                items = self.sections.get(s, [])
                if not items:
                    continue
                addrs = [it.addr for it in items]
                span = []
                for b, (lo, hi) in enumerate(zip(starts, ends)):
                    used = [it for i in range(lo, hi) for it in self.fdata[i].get(s, [])]
                    if used:
                        span.append((b, min(it.addr for it in used), max(it.end for it in used)))
                span = self._named(items, span, starts)
                bounds = {}
                for (pb, plo, phi), (b, lo, hi) in zip(span, span[1:]):
                    window = items[bisect.bisect_left(addrs, phi):bisect.bisect_right(addrs, lo)]
                    cands = [it.addr for it in window if it.addr % UNIT_ALIGN == 0 and not it.is_gap]
                    if cands:
                        bounds[b] = self._pick(items, addrs, cands, lo, starts, pb, b)
                        continue
                    if any(c in self.hard for c in starts[pb + 1:b + 1]):
                        self.notes.append(f"{s}: no boundary fits before {self.text[starts[b]].name}, "
                                          "though the split there is fixed")
                        continue
                    if not self._possible(starts[pb], ends[b]):
                        key = (s, starts[b])
                        if key not in self.unsplit:
                            self.unsplit.add(key)
                            self.notes.append(f"{s}: found no boundary before {self.text[starts[b]].name}")
                        continue
                    # the two blocks and everything between them are one file
                    for c in range(starts[pb] + 1, starts[b] + 1):
                        self.joined[c] = True
                    self.evidence["order " + s] += 1
                    again = True
                    break
                if again:
                    break
                self.bounds[s] = (span, bounds)
            if not again:
                return

    def _named(self, items, span, starts):
        """Widen each block's slice with the named objects of its classes (vtables, statics).

        A named object can sit in another file (a vtable goes where it was first
        needed), so it only counts where it fits between the slices its
        neighbours are known to use.
        """
        hard = {b: (lo, hi) for b, lo, hi in span}
        order = sorted(hard)
        want = defaultdict(list)
        for it in items:
            if it.is_gap or (it.private and not it.name.startswith("@LOCAL@")):
                continue
            k = glue_key(it.name, self.classes)
            if k in self.home:
                want[bisect.bisect_right(starts, self.home[k][0]) - 1].append(it)
        soft = {}
        for b, objs in want.items():
            i = bisect.bisect_left(order, b)
            floor = hard[order[i - 1]][1] if i > 0 else 0
            nxt = i + 1 if i < len(order) and order[i] == b else i
            ceil = hard[order[nxt]][0] if nxt < len(order) else float("inf")
            ok = [it for it in objs if it.addr >= floor and it.end <= ceil]
            if ok:
                lo = min([it.addr for it in ok] + ([hard[b][0]] if b in hard else []))
                hi = max([it.end for it in ok] + ([hard[b][1]] if b in hard else []))
                soft[b] = (lo, hi)
        merged = dict(hard)
        merged.update(soft)
        seq = sorted(merged)
        bad = set()
        for x, y in zip(seq, seq[1:]):
            if merged[x][1] > merged[y][0]:
                bad |= {x, y}
        for b in bad:           # named objects that disagree with each other are dropped
            if b in hard:
                merged[b] = hard[b]
            else:
                del merged[b]
        seq = sorted(merged)
        if any(merged[x][1] > merged[y][0] for x, y in zip(seq, seq[1:])):
            return span
        return [(b, merged[b][0], merged[b][1]) for b in seq]

    def _home_keys(self, lo, hi):
        return {k for k in set(self.keys[lo:hi]) if k and lo <= self.home.get(k, (-1, -1))[0]
                and self.home[k][1] < hi}

    def _pick(self, items, addrs, cands, lo, starts, pb, b):
        ends = starts[1:] + [self.n]
        mine = self._home_keys(starts[b], ends[b])
        theirs = self._home_keys(starts[pb], ends[pb])

        def key_of(it):
            return None if it.private and not it.name.startswith("@LOCAL@") else glue_key(it.name, self.classes)

        def score(c):
            i = bisect.bisect_left(addrs, c)
            sc = 0
            if i > 0 and items[i - 1].is_gap and items[i - 1].size >= 4:
                sc += 3   # padded further than the object needs: a file starts here
            for it in items[i:bisect.bisect_left(addrs, lo)]:
                k = key_of(it)
                sc -= 2 * (k in theirs and k not in mine)
            for it in items[bisect.bisect_left(addrs, cands[0]):i]:
                k = key_of(it)
                sc -= 2 * (k in mine and k not in theirs)
            return (sc, c)
        return max(cands, key=score)

    # --- result ---

    def _existing(self):
        """Units already in the module's splits.txt: name -> {section: (start, end)}."""
        path = ROOT / "config" / self.version / self.module / "splits.txt"
        out, cur = {}, None
        if path.exists():
            for line in path.read_text().splitlines():
                if line and not line[0].isspace() and line.rstrip().endswith(":"):
                    cur = line.rstrip()[:-1]
                    if cur != "Sections":
                        out[cur] = {}
                elif cur and cur != "Sections":
                    m = re.match(r"\s+(\S+)\s+start:0x([0-9A-Fa-f]+)\s+end:0x([0-9A-Fa-f]+)", line)
                    if m:
                        out[cur][m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16))
        return out

    def _finish(self):
        starts = self._starts()
        ends = starts[1:] + [self.n]
        self.units = [Unit(lo, hi) for lo, hi in zip(starts, ends)]
        existing = self._existing()
        fixed = defaultdict(list)
        for ranges in existing.values():
            for s, r in ranges.items():
                fixed[s].append(r)
        sub = self.module[:-1].lower() if self.module.endswith("F") else self.module.lower()
        used_names = {n.rsplit(".", 1)[0] for n in existing}
        for u in self.units:
            fns = self.text[u.lo:u.hi]
            u.fixed = not fns[0].file.startswith("auto_")
            if u.fixed:
                u.name = next((n for n in existing if n.rsplit(".", 1)[0] == fns[0].file), fns[0].file)
            u.ranges[".text"] = (fns[0].addr, fns[-1].end)
            weight = defaultdict(int)
            for i in range(u.lo, u.hi):
                k = self.keys[i]
                if k and u.lo <= self.home.get(k, (-1,))[0] < u.hi:
                    weight[k] += self.text[i].size
            if u.fixed:
                base = None
            elif any(f.name == "_prolog" for f in fns):
                base = "module"
            elif weight:
                base = max(weight, key=weight.get).split("::")[-1]
            else:
                base = f"unit_{fns[0].addr:X}"
            if base is not None:
                name, k = f"game/{sub}/{base}", 2
                while name in used_names:
                    name, k = f"game/{sub}/{base}_{k}", k + 1
                used_names.add(name)
                u.name = name + ".cpp"
            mine = [i for i in self.sinits if u.lo <= i < u.hi]
            if mine:
                order = [self.fidx[c] for c in self.ctors if c in self.fidx]
                pos = [order.index(i) for i in mine]
                u.ranges[".ctors"] = (4 * min(pos), 4 * max(pos) + 4)
                if len(mine) > 1:
                    u.flags.append(f"{len(mine)} static initialisers: more than one file")
            seen = {}
            dups = 0
            for i in range(u.lo, u.hi):
                for it in self.fdata[i].get(".rodata", []):
                    v = literal_value(it)
                    if v is not None and seen.setdefault(v, it.addr) != it.addr:
                        dups += 1
            if dups:
                u.flags.append(f"{dups} repeated literals: probably more than one file")
        for s, (span, bounds) in self.bounds.items():
            items = self.sections[s]
            sec_end = items[-1].end
            owners = []
            for n, (b, lo, hi) in enumerate(span):
                if self.units[b].fixed:
                    continue
                if n == 0:
                    owners.append((b, items[0].addr))
                elif b in bounds:
                    owners.append((b, bounds[b]))
                else:
                    self.units[b].flags.append(f"its {s} could not be told apart from the file before")
            for (b, start), nxt in zip(owners, owners[1:] + [(None, sec_end)]):
                end = nxt[1]
                for fs, fe in sorted(fixed.get(s, [])):
                    if fs <= start < fe:
                        start = fe
                    if start < fs < end:
                        end = fs
                if start < end:
                    self.units[b].ranges[s] = (start, end)


def splits_text(units):
    order = [".text", ".ctors", ".dtors", ".rodata", ".data", ".bss"]
    out = []
    for u in units:
        if u.fixed:
            continue
        out.append(f"{u.name}:")
        for s in order:
            if s in u.ranges:
                a, b = u.ranges[s]
                out.append(f"\t{s:<11} start:0x{a:08X} end:0x{b:08X}")
        out.append("")
    return "\n".join(out)


def report(a, verbose):
    todo = [u for u in a.units if not u.fixed]
    sizes = sorted(u.ranges[".text"][1] - u.ranges[".text"][0] for u in todo)
    flagged = [u for u in a.units if u.flags]
    ev = ", ".join(f"{k} {v}" for k, v in sorted(a.evidence.items()))
    print(f"{a.module}: {a.n} functions -> {len(todo)} proposed units "
          f"({len(a.units) - len(todo)} already split); joins by evidence: {ev}")
    if sizes:
        print(f"  new unit code size: median 0x{sizes[len(sizes) // 2]:X}, largest 0x{sizes[-1]:X}")
    if flagged:
        print(f"  {len(flagged)} units flagged for a closer look (see --list)")
    for note in a.notes[:10]:
        print("  note:", note)
    if verbose:
        for u in a.units:
            t = u.ranges[".text"]
            mark = "" if u.fixed else "new  "
            print(f"  {t[0]:6X}-{t[1]:6X} {u.hi - u.lo:4} fn  {u.name:<50} {mark}{'; '.join(u.flags)}")


def apply(a):
    path = ROOT / "config" / a.version / a.module / "splits.txt"
    text = path.read_text().rstrip("\n") + "\n\n" + splits_text(a.units)
    path.write_text(text.rstrip("\n") + "\n", newline="\n")
    print(f"  wrote {sum(not u.fixed for u in a.units)} units to {path.relative_to(ROOT)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("module", nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--version", default="RMKE01")
    ap.add_argument("--list", action="store_true", help="list every unit")
    ap.add_argument("--splits", action="store_true", help="print splits.txt entries")
    ap.add_argument("--apply", action="store_true", help="append the entries to splits.txt")
    ap.add_argument("--class-gap", type=int, default=16,
                    help="functions of one class this close together count as one file")
    args = ap.parse_args()
    mods = MODULES if args.all else [args.module]
    if not mods[0]:
        ap.error("give a module or --all")
    for mod in mods:
        a = Analysis(args.version, mod, args.class_gap)
        if args.splits:
            print(splits_text(a.units))
            continue
        report(a, args.list)
        if args.apply:
            apply(a)


if __name__ == "__main__":
    main()
